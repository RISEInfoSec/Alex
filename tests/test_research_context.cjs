const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const scope = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../assets/research-context.js'), 'utf8') + '\nthis.context = ResearchContext;', scope);
const {earlier, historical, marker, detail} = scope.context;
const now = new Date('2026-11-01T00:00:00Z');
assert.equal(earlier({year:2021}, now), true);
assert.equal(earlier({year:'2021.0'}, now), true);
assert.equal(earlier({year:2022}, now), false);
assert.equal(earlier({year:''}, now), false);
assert.equal(earlier({year:'unknown'}, now), false);
assert.equal(earlier({year:2020.5}, now), false);
assert.equal(earlier({year:2021, publication_date:'2021-11-02'}, now), false);
assert.equal(earlier({publication_date:'2021-11-01'}, now), true);
assert.equal(earlier({year:2021, publication_date:'2021-02-30'}, now), true);
assert.equal(earlier({publication_date:'2020-02-29'}, new Date('2025-02-27T23:59:59Z')), false);
assert.equal(earlier({publication_date:'2020-02-29'}, new Date('2025-02-28T00:00:00Z')), true);
assert.equal(historical({year:1990}), false);
assert.equal(historical({historical_only:'false'}), false);
assert.equal(historical({historical_only:true}), true);
assert.match(marker({year:1990}), /context-earlier/);
assert.match(marker({historical_only:true}), /context-historical/);
assert.match(detail({year:1990}), /may have been refined or superseded/);
assert.equal(detail({year:2999}), '');
console.log('Research context JavaScript checks passed.');
